/**
 * Winding-path evaluation — the TypeScript mirror of the backend's
 * unit-speed curve layer (api/app/geometry/curves).
 *
 * Everything the editor draws must land exactly where the physics solves
 * it ("drawn = solved"), so this module reproduces the same math: paths
 * are parameterized BY ARC LENGTH (t in [0, L]), the arc is built from
 * (start, end, signed radius) exactly as `CircularArc.from_endpoints`, and
 * the spline is the same centripetal Catmull-Rom with reflected phantom
 * endpoints, evaluated through per-segment cubics with Gauss-Legendre
 * arc-length tables. The shared golden fixture
 * (`editor/__fixtures__/primaryRings.json`, generated by the backend) pins
 * the two implementations together.
 *
 * Turn profiles mirror api/app/models/turn_profiles: cumulative turns over
 * arc length with exact closed-form inverses.
 */
import type { PathSchema, TurnProfileSchema } from '../api/client';
import type { Point } from './coil';

// ---------------------------------------------------------------------------
// Gauss-Legendre (15-point) — exact for the cubic-speed integrands used here
// ---------------------------------------------------------------------------

const GL_NODES = [
  -0.9879925180204854, -0.9372733924007058, -0.8482065834104272,
  -0.7244177313601701, -0.5709721726085388, -0.3941513470775634,
  -0.20119409399743451, 0.0, 0.20119409399743451, 0.3941513470775634,
  0.5709721726085388, 0.7244177313601701, 0.8482065834104272,
  0.9372733924007058, 0.9879925180204854,
];
const GL_WEIGHTS = [
  0.030753241996117203, 0.0703660474881084, 0.10715922046717141,
  0.13957067792615444, 0.16626920581699398, 0.1861610000155622,
  0.1984314853271116, 0.2025782419255613, 0.1984314853271116,
  0.1861610000155622, 0.16626920581699398, 0.13957067792615444,
  0.10715922046717141, 0.0703660474881084, 0.030753241996117203,
];

function glIntegral(f: (u: number) => number, a: number, b: number): number {
  const half = 0.5 * (b - a);
  const mid = 0.5 * (a + b);
  let acc = 0;
  for (let i = 0; i < 15; i++) acc += GL_WEIGHTS[i]! * f(mid + half * GL_NODES[i]!);
  return half * acc;
}

// ---------------------------------------------------------------------------
// Evaluated path: a uniform interface over the three path kinds
// ---------------------------------------------------------------------------

export interface EvaluatedPath {
  /** Total arc length (the parameter domain is [0, length]). */
  length: number;
  /** Point at arc length s. */
  pointAt(s: number): Point;
  /** Unit tangent at arc length s. */
  tangentAt(s: number): Point;
  /** Signed curvature at arc length s (left-normal convention). */
  curvatureAt(s: number): number;
  /** Arc-length parameters sampling the path within the chord tolerance. */
  sampleParams(maxChordError: number): number[];
}

/** Build the evaluated form of a path schema. Throws on degenerate input
 *  (the same conditions the backend rejects). */
export function evaluatePath(path: PathSchema): EvaluatedPath {
  switch (path.kind) {
    case 'line':
      return evalLine(path.start as Point, path.end as Point);
    case 'arc':
      return evalArc(path.start as Point, path.end as Point, path.radius);
    case 'spline':
      return evalSpline(path.points as Point[]);
  }
}

/** The path's defining points, in order — what canvas handles attach to. */
export function pathControlPoints(path: PathSchema): Point[] {
  switch (path.kind) {
    case 'line':
    case 'arc':
      return [path.start as Point, path.end as Point];
    case 'spline':
      return (path.points as Point[]).map((p) => [p[0], p[1]]);
  }
}

/** Replace the i-th control point (immutably). */
export function withControlPoint(path: PathSchema, index: number, p: Point): PathSchema {
  switch (path.kind) {
    case 'line':
    case 'arc':
      return index === 0 ? { ...path, start: p } : { ...path, end: p };
    case 'spline': {
      const points = (path.points as Point[]).map((q, i) => (i === index ? p : q));
      return { ...path, points };
    }
  }
}

/** Translate every defining point of a path by (dr, dz). */
export function translatePath(path: PathSchema, dr: number, dz: number): PathSchema {
  const move = (p: Point): Point => [p[0] + dr, p[1] + dz];
  switch (path.kind) {
    case 'line':
    case 'arc':
      return { ...path, start: move(path.start as Point), end: move(path.end as Point) };
    case 'spline':
      return { ...path, points: (path.points as Point[]).map(move) };
  }
}

/**
 * Repair a path's internal invariants after an edit (immutably; returns the
 * input when nothing needed fixing):
 *  * arc: |radius| is bumped up to half the chord when endpoint drags made
 *    it too small for any circle through both endpoints (sign preserved);
 *  * spline: consecutive duplicate points are dropped (keeping at least 2).
 * A line with coincident endpoints cannot be repaired meaningfully and is
 * returned as-is; rendering guards treat it as empty until the user drags
 * the points apart.
 */
export function normalizePath(path: PathSchema): PathSchema {
  if (path.kind === 'arc') {
    const chord = Math.hypot(
      path.end[0] - path.start[0],
      path.end[1] - path.start[1],
    );
    const minR = chord / 2;
    if (path.radius !== 0 && Math.abs(path.radius) < minR) {
      return { ...path, radius: Math.sign(path.radius) * minR };
    }
    return path;
  }
  if (path.kind === 'spline') {
    const pts = path.points as Point[];
    const dedup: Point[] = [];
    for (const p of pts) {
      const last = dedup[dedup.length - 1];
      if (!last || last[0] !== p[0] || last[1] !== p[1]) dedup.push(p);
    }
    if (dedup.length >= 2 && dedup.length !== pts.length) {
      return { ...path, points: dedup };
    }
    return path;
  }
  return path;
}

/** The path's start/end points without full evaluation. */
export function pathEndpoints(path: PathSchema): { start: Point; end: Point } {
  const pts = pathControlPoints(path);
  return { start: pts[0]!, end: pts[pts.length - 1]! };
}

// ---------------------------------------------------------------------------
// Line
// ---------------------------------------------------------------------------

function evalLine(start: Point, end: Point): EvaluatedPath {
  const dx = end[0] - start[0];
  const dz = end[1] - start[1];
  const length = Math.hypot(dx, dz);
  if (length === 0) throw new Error('Line start and end must differ');
  const ux = dx / length;
  const uz = dz / length;
  return {
    length,
    pointAt: (s) => [start[0] + s * ux, start[1] + s * uz],
    tangentAt: () => [ux, uz],
    curvatureAt: () => 0,
    sampleParams: () => [0, length],
  };
}

// ---------------------------------------------------------------------------
// Arc — mirror of CircularArc.from_endpoints (signed radius: positive bends
// left of the start->end direction; minor arc)
// ---------------------------------------------------------------------------

export interface ArcGeometry {
  center: Point;
  radius: number;
  angleStart: number;
  angleEnd: number; // decreasing range = clockwise traversal
}

export function arcFromEndpoints(start: Point, end: Point, radius: number): ArcGeometry {
  const cx = end[0] - start[0];
  const cz = end[1] - start[1];
  const chord = Math.hypot(cx, cz);
  if (chord === 0) throw new Error('Arc start and end must differ');
  if (radius === 0) throw new Error('Arc radius must be non-zero');
  const r = Math.abs(radius);
  if (r < chord / 2) {
    throw new Error('Arc radius is smaller than half the chord');
  }
  const side = radius > 0 ? 1 : -1;
  const nx = -cz / chord;
  const nz = cx / chord;
  const h = Math.sqrt(Math.max(r * r - (chord / 2) ** 2, 0));
  const center: Point = [
    (start[0] + end[0]) / 2 + side * h * nx,
    (start[1] + end[1]) / 2 + side * h * nz,
  ];
  const angleStart = Math.atan2(start[1] - center[1], start[0] - center[0]);
  const sweep = 2 * Math.asin(Math.min(1, chord / (2 * r)));
  return { center, radius: r, angleStart, angleEnd: angleStart + side * sweep };
}

function evalArc(start: Point, end: Point, signedRadius: number): EvaluatedPath {
  const { center, radius, angleStart, angleEnd } = arcFromEndpoints(start, end, signedRadius);
  const dir = angleEnd > angleStart ? 1 : -1;
  const length = radius * Math.abs(angleEnd - angleStart);
  const angleAt = (s: number) => angleStart + (dir * s) / radius;
  return {
    length,
    pointAt: (s) => {
      const a = angleAt(s);
      return [center[0] + radius * Math.cos(a), center[1] + radius * Math.sin(a)];
    },
    tangentAt: (s) => {
      const a = angleAt(s);
      return [-dir * Math.sin(a), dir * Math.cos(a)];
    },
    curvatureAt: () => dir / radius,
    sampleParams: (tol) => {
      const maxStep =
        (tol >= radius ? Math.PI / 2 : Math.min(2 * Math.acos(1 - tol / radius), Math.PI / 2)) *
        radius;
      const n = Math.max(1, Math.ceil(length / maxStep));
      const out: number[] = [];
      for (let i = 0; i <= n; i++) out.push((length * i) / n);
      return out;
    },
  };
}

// ---------------------------------------------------------------------------
// Centripetal Catmull-Rom spline — mirror of CatmullRomSpline
// ---------------------------------------------------------------------------

/** Cubic coefficients (constant-first) for x and z of one span. */
type SpanCoeffs = { x: number[]; z: number[] };

/** Inverse of the Vandermonde matrix for fit nodes u = 0, 1/3, 2/3, 1 —
 *  recovers exact cubic coefficients from four Barry-Goldman samples. */
const V_INV = [
  [1, 0, 0, 0],
  [-5.5, 9, -4.5, 1],
  [9, -22.5, 18, -4.5],
  [-4.5, 13.5, -13.5, 4.5],
];

function splineSpans(points: Point[]): SpanCoeffs[] {
  if (points.length < 2) throw new Error('Spline needs at least 2 points');
  for (let i = 1; i < points.length; i++) {
    if (points[i]![0] === points[i - 1]![0] && points[i]![1] === points[i - 1]![1]) {
      throw new Error('Consecutive spline points must be distinct');
    }
  }
  const first = points[0]!;
  const second = points[1]!;
  const last = points[points.length - 1]!;
  const prev = points[points.length - 2]!;
  const ext: Point[] = [
    [2 * first[0] - second[0], 2 * first[1] - second[1]],
    ...points,
    [2 * last[0] - prev[0], 2 * last[1] - prev[1]],
  ];

  const spans: SpanCoeffs[] = [];
  for (let k = 0; k < points.length - 1; k++) {
    const quad = ext.slice(k, k + 4) as [Point, Point, Point, Point];
    const tau = [0, 0, 0, 0];
    for (let j = 1; j < 4; j++) {
      const d = Math.hypot(quad[j]![0] - quad[j - 1]![0], quad[j]![1] - quad[j - 1]![1]);
      tau[j] = tau[j - 1]! + Math.sqrt(d);
    }
    const samples: Point[] = [0, 1 / 3, 2 / 3, 1].map((u) =>
      barryGoldman(quad, tau, tau[1]! + u * (tau[2]! - tau[1]!)),
    );
    const cx = [0, 0, 0, 0];
    const cz = [0, 0, 0, 0];
    for (let row = 0; row < 4; row++) {
      for (let col = 0; col < 4; col++) {
        cx[row]! += V_INV[row]![col]! * samples[col]![0];
        cz[row]! += V_INV[row]![col]! * samples[col]![1];
      }
    }
    spans.push({ x: cx, z: cz });
  }
  return spans;
}

function barryGoldman(P: [Point, Point, Point, Point], tau: number[], t: number): Point {
  const lerp = (a: Point, b: Point, ta: number, tb: number): Point => {
    if (tb === ta) return a;
    const w = (t - ta) / (tb - ta);
    return [(1 - w) * a[0] + w * b[0], (1 - w) * a[1] + w * b[1]];
  };
  const A1 = lerp(P[0], P[1], tau[0]!, tau[1]!);
  const A2 = lerp(P[1], P[2], tau[1]!, tau[2]!);
  const A3 = lerp(P[2], P[3], tau[2]!, tau[3]!);
  const B1 = lerp(A1, A2, tau[0]!, tau[2]!);
  const B2 = lerp(A2, A3, tau[1]!, tau[3]!);
  return lerp(B1, B2, tau[1]!, tau[2]!);
}

function spanEval(c: SpanCoeffs, u: number): Point {
  return [
    c.x[0]! + u * (c.x[1]! + u * (c.x[2]! + u * c.x[3]!)),
    c.z[0]! + u * (c.z[1]! + u * (c.z[2]! + u * c.z[3]!)),
  ];
}

function spanDeriv(c: SpanCoeffs, u: number): Point {
  return [
    c.x[1]! + u * (2 * c.x[2]! + 3 * u * c.x[3]!),
    c.z[1]! + u * (2 * c.z[2]! + 3 * u * c.z[3]!),
  ];
}

function spanSecond(c: SpanCoeffs, u: number): Point {
  return [2 * c.x[2]! + 6 * u * c.x[3]!, 2 * c.z[2]! + 6 * u * c.z[3]!];
}

/** Per-span cumulative arc-length table at fixed panel edges. 32 GL-15
 *  panels per span put the quadrature error of a cubic's speed far below
 *  the 1e-9 fixture tolerance. */
const PANELS = 32;

interface SpanTable {
  uEdges: number[];
  sCum: number[]; // cumulative arc length within the span at each edge
}

function buildTable(c: SpanCoeffs): SpanTable {
  const speed = (u: number) => {
    const d = spanDeriv(c, u);
    return Math.hypot(d[0], d[1]);
  };
  const uEdges = [0];
  const sCum = [0];
  for (let i = 0; i < PANELS; i++) {
    const a = i / PANELS;
    const b = (i + 1) / PANELS;
    uEdges.push(b);
    sCum.push(sCum[i]! + glIntegral(speed, a, b));
  }
  return { uEdges, sCum };
}

function evalSpline(points: Point[]): EvaluatedPath {
  const spans = splineSpans(points);
  const tables = spans.map(buildTable);
  const spanS0 = [0];
  for (let k = 0; k < spans.length; k++) {
    spanS0.push(spanS0[k]! + tables[k]!.sCum[PANELS]!);
  }
  const length = spanS0[spans.length]!;

  const locate = (s: number): { k: number; u: number } => {
    const sc = Math.min(Math.max(s, 0), length);
    let k = spanS0.findIndex((v, i) => i < spans.length && sc >= v && sc <= spanS0[i + 1]!);
    if (k < 0) k = spans.length - 1;
    const table = tables[k]!;
    const target = sc - spanS0[k]!;
    // Bracket by table, then safeguarded Newton on the residual
    let i = table.sCum.findIndex((v, idx) => idx < PANELS && target >= v && target <= table.sCum[idx + 1]!);
    if (i < 0) i = target <= 0 ? 0 : PANELS - 1;
    let lo = table.uEdges[i]!;
    let hi = table.uEdges[i + 1]!;
    let sLo = table.sCum[i]!;
    const speed = (u: number) => {
      const d = spanDeriv(spans[k]!, u);
      return Math.hypot(d[0], d[1]);
    };
    const span = table.sCum[i + 1]! - sLo;
    let u = span === 0 ? lo : lo + ((hi - lo) * (target - sLo)) / span;
    for (let iter = 0; iter < 60; iter++) {
      const sU = sLo + (u > lo ? glIntegral(speed, lo, u) : 0);
      const err = sU - target;
      if (Math.abs(err) <= 1e-12 * Math.max(length, 1e-30)) break;
      if (err > 0) {
        hi = u;
      } else {
        lo = u;
        sLo = sU;
      }
      const d = speed(u);
      const uNewton = d > 0 ? u - err / d : NaN;
      u = Number.isFinite(uNewton) && uNewton > lo && uNewton < hi ? uNewton : 0.5 * (lo + hi);
    }
    return { k, u };
  };

  return {
    length,
    pointAt: (s) => {
      const { k, u } = locate(s);
      return spanEval(spans[k]!, u);
    },
    tangentAt: (s) => {
      const { k, u } = locate(s);
      const d = spanDeriv(spans[k]!, u);
      const m = Math.hypot(d[0], d[1]);
      return [d[0] / m, d[1] / m];
    },
    curvatureAt: (s) => {
      const { k, u } = locate(s);
      const d = spanDeriv(spans[k]!, u);
      const dd = spanSecond(spans[k]!, u);
      const sp = Math.hypot(d[0], d[1]);
      return (d[0] * dd[1] - d[1] * dd[0]) / sp ** 3;
    },
    sampleParams: (tol) => {
      // Curvature-driven adaptive subdivision in s, seeded at span edges —
      // same scheme as the backend's CatmullRomSpline._sample.
      const curvatureAt = (s: number) => {
        const { k, u } = locate(s);
        const d = spanDeriv(spans[k]!, u);
        const dd = spanSecond(spans[k]!, u);
        const sp = Math.hypot(d[0], d[1]);
        return Math.abs(d[0] * dd[1] - d[1] * dd[0]) / sp ** 3;
      };
      const out: number[] = [0];
      const minStep = length * 1e-9;
      const stack: Array<[number, number]> = [];
      for (let k = spans.length - 1; k >= 0; k--) stack.push([spanS0[k]!, spanS0[k + 1]!]);
      while (stack.length) {
        const [a, b] = stack.pop()!;
        const ds = b - a;
        const kap = 1.5 * Math.max(curvatureAt(a), curvatureAt((a + b) / 2), curvatureAt(b));
        if (ds > minStep && (ds * ds * kap) / 8 > tol) {
          const mid = (a + b) / 2;
          stack.push([mid, b]);
          stack.push([a, mid]);
        } else {
          out.push(b);
        }
      }
      return out;
    },
  };
}

// ---------------------------------------------------------------------------
// Turn profiles — mirror of app/models/turn_profiles (exact inverses)
// ---------------------------------------------------------------------------

export interface EvaluatedTurns {
  totalTurns: number;
  /** Cumulative turns at arc length s. */
  at(s: number): number;
  /** Arc length at which the cumulative count reaches n (exact inverse). */
  inverse(n: number): number;
}

export function evaluateTurns(profile: TurnProfileSchema, pathLength: number): EvaluatedTurns {
  if (profile.kind === 'uniform') {
    const total = profile.total_turns;
    return {
      totalTurns: total,
      at: (s) => (total * s) / pathLength,
      inverse: (n) => (pathLength * n) / total,
    };
  }
  // graded: piecewise-linear cumulative over (u * L, n) breakpoints
  const sPts = profile.points.map((p) => p[0] * pathLength);
  const nPts = profile.points.map((p) => p[1]);
  const last = nPts.length - 1;
  return {
    totalTurns: nPts[last]!,
    at: (s) => {
      if (s <= sPts[0]!) return nPts[0]!;
      if (s >= sPts[last]!) return nPts[last]!;
      let i = 0;
      while (i < last - 1 && sPts[i + 1]! <= s) i++;
      const frac = (s - sPts[i]!) / (sPts[i + 1]! - sPts[i]!);
      return nPts[i]! + frac * (nPts[i + 1]! - nPts[i]!);
    },
    inverse: (n) => {
      if (n <= nPts[0]!) return sPts[0]!;
      if (n >= nPts[last]!) return sPts[last]!;
      let i = 0;
      while (i < last - 1 && nPts[i + 1]! <= n) i++;
      const frac = (n - nPts[i]!) / (nPts[i + 1]! - nPts[i]!);
      return sPts[i]! + frac * (sPts[i + 1]! - sPts[i]!);
    },
  };
}
